# Rumus: Keliling = 12 x sisi
# Karena kubus punya 12 rusuk yang sama panjang

print("=== Menghitung Keliling Rusuk Kubus ===")
print("Rumus: Keliling = 12 x sisi")

# Minta input panjang sisi dari pengguna
sisi = float(input("Masukkan panjang sisi kubus (cm): "))

# Hitung keliling rusuk
keliling = 12 * sisi

# Tampilkan hasil
print(f"\nPanjang sisi = {sisi} cm")
print(f"Cara hitung: 12 x {sisi} = {keliling}")
print(f"Jadi, keliling rusuk kubus adalah {keliling} cm")
